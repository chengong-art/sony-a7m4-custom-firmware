#!/usr/bin/env python3
"""Build `A7M4 ToolKit.app`, a macOS launcher for this port.

The bundle is thin: `Contents/MacOS/launch` finds a Python >= 3.11 and runs
`advanced-macos/gui/app.py`, which relays the reviewed entry points into a window
instead of spawning a Terminal. The GUI source is a real file in the repo (so it
is linted and tested), not a string embedded here.

The generated bundle is a local build artifact (git-ignored); this script is the
reproducible source of it.
"""
from __future__ import annotations

import argparse
import shutil
import struct
import subprocess
import sys
import zlib
from pathlib import Path

APP_NAME = "A7M4 ToolKit"

INFO_PLIST = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>{name}</string>
  <key>CFBundleDisplayName</key><string>{name}</string>
  <key>CFBundleIdentifier</key><string>local.a7m4.toolkit.launcher</string>
  <key>CFBundleVersion</key><string>{version}</string>
  <key>CFBundleShortVersionString</key><string>{version}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.utilities</string>
</dict>
</plist>
"""

# The wrapper only has to find a usable interpreter and hand over to app.py.
WRAPPER = """#!/bin/bash
# Generated by tools/make_app_macos.py. Finds a Python >= 3.11 and runs the GUI.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
RESOURCES="$(cd "$HERE/../Resources" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"

python_ok() {
  [ -x "$1" ] && "$1" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 11) else 1)' >/dev/null 2>&1
}

PYTHON=""
for candidate in \\
  "$ROOT/.venv/bin/python" \\
  "$ROOT/venv/bin/python" \\
  "${A7M4_PYTHON:-}" \\
  python3.13 python3.12 python3.11 python3
do
  [ -n "$candidate" ] || continue
  if [ -x "$candidate" ]; then
    resolved="$candidate"
  else
    resolved="$(command -v "$candidate" 2>/dev/null || true)"
  fi
  [ -n "$resolved" ] || continue
  if python_ok "$resolved"; then PYTHON="$resolved"; break; fi
done

if [ -z "$PYTHON" ]; then
  /usr/bin/osascript -e 'display alert "A7M4 ToolKit" message "Python 3.11+ not found. Install it, or run advanced-macos/_launch.sh from Terminal." as critical' >/dev/null 2>&1
  exit 2
fi

export A7M4_TOOLKIT_ROOT="$ROOT"
exec -a "A7M4 ToolKit" "$PYTHON" -B "$RESOURCES/app.py" "$@"
"""


def _png(width: int, height: int, pixels: bytearray) -> bytes:
    raw = bytearray()
    stride = width * 4
    for y in range(height):
        raw.append(0)
        raw += pixels[y * stride:(y + 1) * stride]

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
            + chunk(b"IEND", b""))


def master_icon(size: int = 1024) -> bytearray:
    """A quiet camera glyph: rounded dark tile, lens ring, red record dot."""
    pixels = bytearray(size * size * 4)
    radius = size * 0.22
    cx = cy = (size - 1) / 2
    lens_r = size * 0.30
    ring = size * 0.035
    dot = (size * 0.735, size * 0.265, size * 0.075)
    for y in range(size):
        for x in range(size):
            dx = max(abs(x - cx) - (size / 2 - radius), 0.0)
            dy = max(abs(y - cy) - (size / 2 - radius), 0.0)
            if (dx * dx + dy * dy) ** 0.5 > radius:
                continue
            r, g, b, a = 28, 28, 30, 255
            dist = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            if lens_r - ring <= dist <= lens_r:
                r = g = b = 235
            elif dist < lens_r - ring:
                shade = int(70 + 40 * (dist / max(lens_r, 1)))
                r = shade // 2
                g = shade // 2 + 6
                b = shade // 2 + 14
            if ((x - dot[0]) ** 2 + (y - dot[1]) ** 2) ** 0.5 <= dot[2]:
                r, g, b = 226, 74, 66
            i = (y * size + x) * 4
            pixels[i:i + 4] = bytes((r, g, b, a))
    return pixels


def downscale(src: bytearray, src_size: int, dst_size: int) -> bytearray:
    if src_size == dst_size:
        return src
    out = bytearray(dst_size * dst_size * 4)
    ratio = src_size / dst_size
    for y in range(dst_size):
        y0, y1 = int(y * ratio), max(int((y + 1) * ratio), int(y * ratio) + 1)
        for x in range(dst_size):
            x0, x1 = int(x * ratio), max(int((x + 1) * ratio), int(x * ratio) + 1)
            r = g = b = a = 0
            n = 0
            for sy in range(y0, min(y1, src_size)):
                base = sy * src_size * 4
                for sx in range(x0, min(x1, src_size)):
                    i = base + sx * 4
                    r += src[i]
                    g += src[i + 1]
                    b += src[i + 2]
                    a += src[i + 3]
                    n += 1
            n = max(n, 1)
            i = (y * dst_size + x) * 4
            out[i:i + 4] = bytes((r // n, g // n, b // n, a // n))
    return out


def build_icon(resources: Path) -> bool:
    master_size = 1024
    master = master_icon(master_size)
    iconset = resources / "icon.iconset"
    if iconset.exists():
        shutil.rmtree(iconset)
    iconset.mkdir(parents=True)
    for size in (16, 32, 64, 128, 256, 512):
        for scale, suffix in ((1, ""), (2, "@2x")):
            px = size * scale
            (iconset / f"icon_{size}x{size}{suffix}.png").write_bytes(
                _png(px, px, downscale(master, master_size, px)))
    result = subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(resources / "icon.icns")],
                            capture_output=True, text=True)
    shutil.rmtree(iconset, ignore_errors=True)
    if result.returncode != 0:
        print(f"icon generation skipped: {result.stderr.strip()}", file=sys.stderr)
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path, default=None,
                        help="where to put the .app (defaults to the repo root)")
    args = parser.parse_args()

    repo = Path(__file__).resolve().parents[1]
    destination = (args.destination or repo).resolve()
    gui_source = repo / "advanced-macos/gui/app.py"
    if not gui_source.is_file():
        print(f"GUI source missing: {gui_source}", file=sys.stderr)
        return 2

    app = destination / f"{APP_NAME}.app"
    if app.exists():
        shutil.rmtree(app)
    (app / "Contents/MacOS").mkdir(parents=True)
    (app / "Contents/Resources").mkdir(parents=True)

    version = "0.2.0"
    pyproject = repo / "pyproject.toml"
    if pyproject.exists():
        for line in pyproject.read_text("utf8").splitlines():
            if line.startswith("version = "):
                version = line.split('"')[1]
                break

    (app / "Contents/Info.plist").write_text(INFO_PLIST.format(name=APP_NAME, version=version), "utf8")
    wrapper = app / "Contents/MacOS/launch"
    wrapper.write_text(WRAPPER, "utf8")
    wrapper.chmod(0o755)
    shutil.copy2(gui_source, app / "Contents/Resources/app.py")

    # Every entry point must be executable, or the child process cannot start.
    entries = sorted((repo / "advanced-macos").glob("*.command"))
    for entry in entries:
        entry.chmod(entry.stat().st_mode | 0o111)

    icons = build_icon(app / "Contents/Resources")

    print({"app": str(app), "icon": icons, "version": version,
           "entries": len(entries), "gui_source": str(gui_source), "camera_io": False})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
